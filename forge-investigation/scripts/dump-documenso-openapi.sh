#!/usr/bin/env bash
# Produces the Documenso v2 OpenAPI document from Documenso's source, for
# environments that cannot reach https://app.documenso.com/api/v2-beta/openapi.json
# (the URL .speakeasy/workflow.yaml normally pulls from).
#
# Usage: scripts/dump-documenso-openapi.sh <out.json> [documenso-git-ref]
set -euo pipefail
out=$(realpath -m "${1:?usage: $0 <out.json> [ref]}")
ref=${2:-main}
here=$(cd "$(dirname "$0")" && pwd)
work=${DOCUMENSO_WORK:-$(mktemp -d)}

if [ ! -d "${work}/documenso/.git" ]; then
  git clone --depth 1 --branch "${ref}" https://github.com/documenso/documenso "${work}/documenso"
fi
cd "${work}/documenso"
npm install --ignore-scripts --no-audit --no-fund
(cd packages/prisma && NEXT_PRIVATE_DATABASE_URL=postgres://x@localhost/x npx prisma generate)

cat > packages/trpc/dump-openapi.ts <<TS
import { writeFileSync } from 'node:fs';
import { openApiDocument } from './server/open-api';
writeFileSync(process.env.OUT!, JSON.stringify(openApiDocument, null, 2));
TS
# The router's import graph pulls in i18n that fails without a Babel build, but the
# document is already generated by then, so tolerate a non-zero exit if it exists.
rm -f "${out}"
(cd packages/trpc && OUT="${out}" NEXT_PUBLIC_WEBAPP_URL=https://app.documenso.com \
  NEXT_PRIVATE_DATABASE_URL=postgres://x@localhost/x \
  NODE_OPTIONS="--require ${here}/documenso-shims/register.cjs" npx tsx dump-openapi.ts) || true
test -s "${out}" || { echo "error: failed to produce ${out}" >&2; exit 1; }
echo "wrote ${out} from documenso@$(git rev-parse --short HEAD)"
